#!/usr/bin/env python3
"""Generate the resampler table the DSP needs (pure Python, no numpy).

Rings runs at its own frame rate: rings/dsp/dsp.h names kSampleRate =
48000, and every pitch (a3 = 440 / kSampleRate), envelope, filter, delay line
and reverb time in the DSP is a count of samples or 24-sample blocks at that
rate. The DSP is run here exactly as the hardware runs it and its output is
resampled from 48 kHz to Move's 44.1 kHz.

44100 / 48000 = 147 / 160, so every output sample sits at input time
n * 160/147, whose fractional part is r/147. The kernel is a Kaiser-windowed
sinc tabulated at RS_PHASES fractional positions (plus one guard row); the
resampler interpolates linearly between adjacent rows. Each row is normalised
to unity DC gain so DC never becomes a ripple.

Copyright (c) 2026 Hiro Ikezawa. MIT License (see LICENSE).
"""
import math
import pathlib
import sys


def i0(x):
    """Modified Bessel function of the first kind, order 0 (series)."""
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2.0 * k)) ** 2
        s += term
        k += 1
    return s


def kaiser(t, half, beta):
    r = t / half
    if abs(r) > 1.0:
        return 0.0
    return i0(beta * math.sqrt(1.0 - r * r)) / i0(beta)


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


IN_RATE = 48000.0                  # rings/dsp/dsp.h kSampleRate
RS_UP, RS_DOWN = 147, 160          # 44100 / IN_RATE, exactly
assert abs(IN_RATE * RS_UP / RS_DOWN - 44100.0) < 1e-9
RS_PHASES = 256                    # tabulated fractional positions
RS_TAPS = 64
RS_HALF = RS_TAPS // 2             # taps k = -31..32 around the output time
RS_CUTOFF_HZ = 22050.0             # -6 dB at Move's Nyquist
RS_BETA = 7.0                      # ~70 dB stopband
fc = RS_CUTOFF_HZ / IN_RATE        # cycles per input sample

rows = []
for p in range(RS_PHASES + 1):
    frac = p / RS_PHASES
    row = []
    for k in range(-RS_HALF + 1, RS_HALF + 1):
        t = frac - k
        row.append(2.0 * fc * sinc(2.0 * fc * t) * kaiser(t, RS_HALF + 0.5, RS_BETA))
    g = sum(row)
    rows.append([v / g for v in row])


def fmt(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join("%.9ef" % v for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


out = ["/* Generated by scripts/gen_tables.py. Do not edit. */",
       "#pragma once",
       "",
       "#define ORINGS_RS_UP %d" % RS_UP,
       "#define ORINGS_RS_DOWN %d" % RS_DOWN,
       "#define ORINGS_RS_PHASES %d" % RS_PHASES,
       "#define ORINGS_RS_TAPS %d" % RS_TAPS,
       "#define ORINGS_RS_HALF %d" % RS_HALF,
       "",
       "/* orings_rs_table[p][j]: weight of input sample q + (j - ORINGS_RS_HALF + 1)",
       " * for the output at input time q + p/ORINGS_RS_PHASES (row PHASES = guard). */",
       "static const float orings_rs_table[ORINGS_RS_PHASES + 1][ORINGS_RS_TAPS] = {"]
for row in rows:
    out.append(" {")
    out.append(fmt(row))
    out.append(" },")
out.append("};")
out.append("")

# --- oRings FX: Move's 44.1 kHz input -> Rings' 48 kHz (the IN jack). -----
# 48000 / 44100 = 160 / 147: a fixed polyphase FIR, one phase per output
# (UP_L = 160 phases, the phase advancing by UP_M = 147 per output, the input
# position by floor((p + M) / L)) -- integer arithmetic, so nothing drifts.
# The prototype is designed at L * 44.1 kHz and cut off at 20 kHz, below
# both Nyquists, so the 48 kHz signal holds only what the 44.1 kHz one did.
# Each phase is normalised to unity DC gain. UP_K taps per phase, stored
# oldest-first for a forward dot product over the history.
UP_L, UP_M, UP_K = 160, 147, 32
UP_CUTOFF_HZ = 20000.0
UP_BETA = 8.0
assert 44100 * UP_L == 48000 * UP_M
n = UP_L * UP_K
fs_up = UP_L * 44100.0
fcu = UP_CUTOFF_HZ / fs_up
centre = (n - 1) / 2.0
i0b = i0(UP_BETA)
h = []
for i in range(n):
    t = i - centre
    s_ = 2.0 * fcu if t == 0 else math.sin(2.0 * math.pi * fcu * t) / (math.pi * t)
    w = i0(UP_BETA * math.sqrt(max(0.0, 1.0 - (t / centre) ** 2))) / i0b
    h.append(s_ * w)
up = []
for ph in range(UP_L):
    taps = [h[ph + k * UP_L] for k in range(UP_K)]
    g = sum(taps)
    up.extend(v / g for v in reversed(taps))
# Group delay in 44.1 kHz input samples: the FIR's centre over L.
out += ["#define ORINGS_UP_L %d" % UP_L,
        "#define ORINGS_UP_M %d" % UP_M,
        "#define ORINGS_UP_K %d" % UP_K,
        "/* orings_up_table[p * K + k]: phase p, history oldest (k = 0) .. newest. */",
        "static const float orings_up_table[ORINGS_UP_L * ORINGS_UP_K] = {",
        fmt(up), "};", ""]

path = pathlib.Path(sys.argv[1])
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text("\n".join(out))
